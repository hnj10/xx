def main():
    chars = json.load(io.open(MANIFEST, encoding='utf-8'))
    missing = [c['name'] for c in chars if c['name'] not in APPEARANCE]
    print('总数', len(chars), '设定缺失', len(missing), missing)

    # 输出完整 prompt 清单供后续 ImageGen 使用
    rows = []
    for c in chars:
        elem, desc = APPEARANCE.get(c['name'], ('?', '通用原神风格角色'))
        prompt = '%s,%s%s' % (c['name'], desc, STYLE)
        rows.append((c['name'], c['file'], elem, prompt))

    out = r'C:/Users/20285/IdeaProjects/xx/gen_char_prompts.json'
    json.dump([{'name': n, 'file': f, 'element': e, 'prompt': p}
               for n, f, e, p in rows],
              io.open(out, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('prompts written ->', out, len(rows))

if __name__ == '__main__':
    main()
