// 取角色立绘 URL；没有图片时返回空字符串（模板里 v-if 判断）
export function charImg(name) {
  const f = CHAR_NAME_TO_FILE[name]
  if (!f) return ''
  return charFiles[`../assets/chars/${f}.png`] || ''
}

// 从「圣遗物 4件套」等文案中解析套装名并返回图标 URL；没有则返回空
export function artifactImg(text) {
  if (!text) return ''
  for (const [k, f] of Object.entries(ARTIFACT_NAME_TO_FILE)) {
    if (text.includes(k)) {
      return artifactFiles[`../assets/artifacts/${f}.png`] || ''
    }
  }
  return ''
}
